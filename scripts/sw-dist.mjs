// Runs after `vite build` (npm run build): writes dist/sw.js, the service worker that makes the
// app installable (Quest Browser's "Install") and keeps it working offline after the first visit.
// It caches every built file under a name made from their contents, so each new build replaces
// the old cache. The page itself and ./__version.json come from the network when it's there, so a
// new build shows up at once. The dev server never registers it (src/main.js).
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'dist');
const name = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).name;

const files = [];
const walk = (d) => {
  for (const e of readdirSync(d, { withFileTypes: true })) {
    const p = join(d, e.name);
    if (e.isDirectory()) walk(p);
    else files.push(relative(dist, p).split(sep).join('/'));
  }
};
walk(dist);
const cached = files.filter((f) => f !== 'sw.js' && f !== 'index.html').sort();
const hash = createHash('sha256');
for (const f of ['index.html', ...cached]) hash.update(f).update(readFileSync(join(dist, f)));
const cache = `${name}-${hash.digest('hex').slice(0, 12)}`;

// './' rather than 'index.html': some hosts redirect index.html to the folder, and a redirected
// response can't answer a page load.
const sw = `// Generated by scripts/sw-dist.mjs. Offline copy of the app.
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(['./', ...cached], null, 2)};
const FRESH = (url) => url.pathname.endsWith('/__version.json'); // besides pages: fresh when online

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  const old = (k) => k.startsWith(${JSON.stringify(`${name}-`)}) && k !== CACHE;
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter(old).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  if (req.mode === 'navigate' || FRESH(url)) {
    // The page (and the version it shows): fresh when online, the cached copy offline.
    e.respondWith(fetch(req).catch(async () => (await caches.match(req, { ignoreSearch: true })) ?? caches.match('./')));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit ?? fetch(req)));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`dist/sw.js  ${cache}, ${cached.length + 1} files cached`);
